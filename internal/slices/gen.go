//go:build ignore

// gen writes the file that blank-imports every slice package under the
// current directory, so that each slice registers itself with the app.
// Run it with `go generate ./...`.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/build"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const slicesPath = "heinzel/internal/slices"

func main() {
	out := flag.String("o", "slices_gen.go", "output file")
	flag.Parse()
	if doc, err := parser.ParseFile(token.NewFileSet(), "doc.go", nil, parser.PackageClauseOnly); err != nil || doc.Name.Name != "slices" {
		log.Fatal("gen.go must run from internal/slices (no doc.go of package slices here); use go generate ./...")
	}

	entries, err := os.ReadDir(".")
	if err != nil {
		log.Fatal(err)
	}
	var dirs []string
	for _, entry := range entries {
		ok, err := isSliceDir(".", entry)
		if err != nil {
			log.Fatal(err)
		}
		if ok {
			dirs = append(dirs, entry.Name())
		}
	}
	slices.Sort(dirs)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen.go; DO NOT EDIT.\n\n")
	buf.WriteString("package slices\n\n")
	buf.WriteString("import (\n")
	for _, dir := range dirs {
		fmt.Fprintf(&buf, "\t_ %q\n", slicesPath+"/"+dir)
	}
	buf.WriteString(")\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// isSliceDir reports whether entry, found in parent, is a slice package. It
// must stay identical to the copy in slicedirs_test.go, which documents the
// rule; TestGenUsesTheSameSliceDirRule enforces that.
func isSliceDir(parent string, entry fs.DirEntry) (bool, error) {
	name := entry.Name()
	if !entry.IsDir() || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
		return false, nil
	}
	pkg, err := build.Default.ImportDir(filepath.Join(parent, name), 0)
	var noGo *build.NoGoError
	if errors.As(err, &noGo) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return len(pkg.GoFiles) > 0, nil
}
