//! Generates the slice wiring: one module per directory under `src/slices/`,
//! plus the list of their factories, so adding a slice directory is enough
//! to wire the slice in.

#[path = "build/slice_dirs.rs"]
mod slice_dirs;

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-changed=src/slices");
    println!("cargo::rerun-if-changed=build/slice_dirs.rs");

    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"),
    );
    let root = manifest_dir.join("src").join("slices");
    let names = match slice_dirs::slice_dirs(&root) {
        Ok(names) => names,
        Err(err) => panic!("{err}"),
    };

    let mut out = String::from(
        "// Generated by build.rs from the directories under src/slices; do not edit.\n",
    );
    for name in &names {
        let module = root.join(name).join("mod.rs");
        writeln!(
            out,
            "\n#[path = {:?}]\npub mod {name};",
            module.display().to_string()
        )
        .expect("write to a String");
    }
    let factories: Vec<String> = names
        .iter()
        .map(|name| format!("{name}::FACTORY"))
        .collect();
    let quoted: Vec<String> = names.iter().map(|name| format!("{name:?}")).collect();
    writeln!(
        out,
        "\n/// Every slice's factory, in slice-name order.\npub const FACTORIES: &[crate::app::Factory] = &[{}];\n\n/// Every slice's name, in the same order as [`FACTORIES`].\npub const NAMES: &[&str] = &[{}];",
        factories.join(", "),
        quoted.join(", "),
    )
    .expect("write to a String");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("slices.rs"), out).expect("write the generated slice wiring");
}
